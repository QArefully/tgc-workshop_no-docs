/** Country-aware resolver useful to non-React presentation tests and adapters. */
export function createRepeatBuyingTranslator(country: Country) {
  const boundTranslate = (key: RepeatBuyingMessageKey, params: MessageParams = {}) =>
    translate(repeatBuyingMessages, country, key, params);
  return Object.assign(boundTranslate, {
    country,
    formatCount: (value: number) => formatCount(value, country),
    formatWeightGrams: (value: number) => formatWeightGrams(value, country),
  });
}
