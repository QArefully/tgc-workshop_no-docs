/**
 * Buyer-facing copy for company, approval, notification, schedule, and mailbox surfaces.
 *
 * Snapshot fields (notification title/body, legacy mailbox subject/body) remain untouched by the
 * web client. These messages are used for current UI labels and for typed mailbox descriptors,
 * where the descriptor's country is the locale authority.
 */
function message(
  uk: MessageTemplate,
  cn: MessageTemplate,
  pl: MessageTemplate,
  es: MessageTemplate,
  de: MessageTemplate,
  fr: MessageTemplate,
): CountryMessageSet {
  return { UK: uk, US: uk, CN: cn, PL: pl, ES: es, DE: de, FR: fr };
}

